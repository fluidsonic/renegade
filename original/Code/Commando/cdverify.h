#if defined(_MSC_VER)
#pragma once
#endif

#ifndef __CDVERIFY_H
#define __CDVERIFY_H

#include "notify.h"


//////////////////////////////////////////////////////////////////////
//	Forward declarations
//////////////////////////////////////////////////////////////////////
class StringClass;
class CDVerifyClass;


//////////////////////////////////////////////////////////////////////
//
//	CDVerifyEvent
//
//////////////////////////////////////////////////////////////////////
class CDVerifyEvent : public TypedEventPtr<CDVerifyEvent, CDVerifyClass>
{
public:

	///////////////////////////////////////////////////////////////////
	//	Public constants
	///////////////////////////////////////////////////////////////////
	typedef enum
	{
		NOT_VERIFIED = 0,
		VERIFIED,
	} EventID;

	///////////////////////////////////////////////////////////////////
	//	Public constructors/destructors
	///////////////////////////////////////////////////////////////////
	CDVerifyEvent (EventID event, CDVerifyClass *object)	:
		TypedEventPtr<CDVerifyEvent, CDVerifyClass>(object),
		MyEventID (event)  {}

	~CDVerifyEvent (void) {}

	///////////////////////////////////////////////////////////////////
	//	Public methods
	///////////////////////////////////////////////////////////////////

	//
	//	Inherited
	//
	inline EventID		Event (void) const	{ return MyEventID; }
	
private:
	
	///////////////////////////////////////////////////////////////////
	//	Private member data
	///////////////////////////////////////////////////////////////////
	EventID MyEventID;
};


//////////////////////////////////////////////////////////////////////
//
//	CDVerifyClass
//
//////////////////////////////////////////////////////////////////////
class CDVerifyClass : public Notifier<CDVerifyEvent>
{
public:

	///////////////////////////////////////////////////////////////////
	//	Public constructors/destructors
	///////////////////////////////////////////////////////////////////
	CDVerifyClass  (void) {}
	~CDVerifyClass (void) {}

	///////////////////////////////////////////////////////////////////
	//	Public methods
	///////////////////////////////////////////////////////////////////

	bool		Get_CD_Path (StringClass &drive_path);
	void		Display_UI (Observer<CDVerifyEvent> *observer);
	
private:
	
	///////////////////////////////////////////////////////////////////
	//	Private member data
	///////////////////////////////////////////////////////////////////
};


#endif //__CDVERIFY_H
