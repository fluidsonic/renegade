void
PathDebugPlotterClass::Render_Vector
(
	RenderInfoClass &	rinfo,
	const Vector3 &	pt,
	const Vector3 &	vec,
	const Vector3 &	color
)
{
	if (vec.Length2() < WWMATH_EPSILON) return;

	PhysicsSceneClass::Get_Instance ()->Add_Debug_Vector (pt, vec, color);
	
	return ;
}

